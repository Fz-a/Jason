const dictionaries: Record<Locale, Dict> = {
	en,
	"zh-Hans": zhHans,
	"zh-Hant": zhHant,
};

export const LOCALE_OPTIONS: { id: Locale; short: string; title: string }[] = [
	{ id: "en", short: "EN", title: "English" },
	{ id: "zh-Hant", short: "繁", title: "繁體中文" },
	{ id: "zh-Hans", short: "简", title: "简体中文" },
];

type LocaleContextValue = {
	locale: Locale;
	setLocale: (locale: Locale) => void;
	t: (key: string) => string;
	isZh: boolean;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);
const CopyOverrideContext = createContext<Dict>({});

export function getDict(locale: Locale): Dict {
	return dictionaries[locale];
}

/** Merge Studio / page-layout copy overrides into `t()`. */
export function CopyOverrideProvider({
	overrides,
	children,
}: {
	overrides: Dict;
	children: ReactNode;
}) {
	return (
		<CopyOverrideContext.Provider value={overrides}>
			{children}
		</CopyOverrideContext.Provider>
	);
}

export function LocaleProvider({ children }: { children: ReactNode }) {
	const setLocale = useCallback((_next: Locale) => {
		/* Site is English-only for now */
	}, []);

	useEffect(() => {
		document.documentElement.lang = "en";
	}, []);

	const value = useMemo<LocaleContextValue>(
		() => ({
			locale: "en",
			setLocale,
			t: (key: string) => dictionaries.en[key] ?? key,
			isZh: false,
		}),
		[setLocale],
	);

	return (
		<LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
	);
}

export function useLocale() {
	const ctx = useContext(LocaleContext);
	const overrides = useContext(CopyOverrideContext);
	if (!ctx) {
		throw new Error("useLocale must be used within LocaleProvider");
	}
	const t = useCallback(
		(key: string) => overrides[key] ?? ctx.t(key),
		[ctx, overrides],
	);
	return { ...ctx, t };
}
